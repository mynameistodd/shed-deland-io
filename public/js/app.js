const ALL_PHOTOS = CHAPTERS.flatMap((ch) =>
  ch.photos.map((p) => ({
    ...p,
    chapterId: ch.id,
    chapterBadge: ch.badge
  }))
);

document.addEventListener("DOMContentLoaded", () => {
  const yearEl = document.getElementById("year");
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  initTheme();
  renderChapters("all");
  initFilters();
  initLightbox();
});

function initTheme() {
  const saved = localStorage.getItem("shed-theme");
  const initial = saved || "dark";
  document.documentElement.setAttribute("data-theme", initial);

  const btn = document.getElementById("theme-toggle");
  if (!btn) return;
  btn.addEventListener("click", () => {
    const current = document.documentElement.getAttribute("data-theme") || "dark";
    const next = current === "dark" ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", next);
    localStorage.setItem("shed-theme", next);
  });
}

function renderChapters(filter) {
  const container = document.getElementById("chapters-container");
  if (!container) return;

  const visibleChapters =
    filter === "all" ? CHAPTERS : CHAPTERS.filter((ch) => ch.id === filter);

  container.innerHTML = visibleChapters
    .map(
      (ch) => `
      <div class="chapter-block" data-chapter="${ch.id}">
        <div class="chapter-meta">
          <span class="chapter-badge">${ch.badge}</span>
          <span class="chapter-date">${ch.dateRange}</span>
        </div>
        <h3 class="chapter-title">${ch.title}</h3>
        <p class="chapter-desc">${ch.description}</p>
        <div class="photo-grid">
          ${ch.photos
            .map(
              (photo) => `
            <button class="photo-card" data-photo-id="${photo.id}" aria-label="Open photo: ${photo.title}">
              <div class="photo-thumb-wrap">
                <img src="${photo.src}" alt="${photo.title} - ${photo.caption}" loading="lazy" />
                <span class="photo-date-tag">${photo.date}</span>
              </div>
              <div class="photo-info">
                <div class="photo-title">${photo.title}</div>
                <div class="photo-caption">${photo.caption}</div>
              </div>
            </button>
          `
            )
            .join("")}
        </div>
      </div>
    `
    )
    .join("");
}

function initFilters() {
  const pills = document.querySelectorAll(".filter-pill");
  pills.forEach((pill) => {
    pill.addEventListener("click", () => {
      pills.forEach((p) => p.classList.remove("active"));
      pill.classList.add("active");
      const filter = pill.getAttribute("data-filter") || "all";
      renderChapters(filter);
    });
  });
}

function initLightbox() {
  const lightbox = document.getElementById("lightbox");
  const lbImg = document.getElementById("lb-img");
  const lbTitle = document.getElementById("lb-title");
  const lbCaption = document.getElementById("lb-caption");
  const lbDate = document.getElementById("lb-date");
  const lbChapter = document.getElementById("lb-chapter");
  const lbCounter = document.getElementById("lb-counter");
  const prevBtn = document.getElementById("lb-prev");
  const nextBtn = document.getElementById("lb-next");

  let currentIndex = 0;

  function openAt(index) {
    currentIndex = (index + ALL_PHOTOS.length) % ALL_PHOTOS.length;
    const item = ALL_PHOTOS[currentIndex];
    lbImg.src = item.src;
    lbImg.alt = item.title;
    lbTitle.textContent = item.title;
    lbCaption.textContent = item.caption;
    lbDate.textContent = item.date;
    lbChapter.textContent = item.chapterBadge;
    lbCounter.textContent = `${currentIndex + 1} / ${ALL_PHOTOS.length}`;
    lightbox.classList.add("open");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  }

  function closeLightbox() {
    lightbox.classList.remove("open");
    lightbox.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
  }

  document.addEventListener("click", (e) => {
    const trigger = e.target.closest("[data-photo-id]");
    if (trigger) {
      const id = trigger.getAttribute("data-photo-id");
      const idx = ALL_PHOTOS.findIndex((p) => p.id === id);
      if (idx !== -1) openAt(idx);
      return;
    }

    if (e.target.closest("[data-close-lightbox]")) {
      closeLightbox();
    }
  });

  prevBtn.addEventListener("click", (e) => {
    e.stopPropagation();
    openAt(currentIndex - 1);
  });

  nextBtn.addEventListener("click", (e) => {
    e.stopPropagation();
    openAt(currentIndex + 1);
  });

  document.addEventListener("keydown", (e) => {
    if (!lightbox.classList.contains("open")) return;
    if (e.key === "Escape") closeLightbox();
    if (e.key === "ArrowLeft") openAt(currentIndex - 1);
    if (e.key === "ArrowRight") openAt(currentIndex + 1);
  });
}
